"""Generate the system files that go into system_a next to the priv-apps:
  etc/permissions/privapp-permissions-futureos.xml  - every privileged permission each APK requests
      (ro.control_privapp_permissions=enforce: a missing entry = bootloop)
  etc/excluded-input-devices.xml                     - InputManager ignores the touch panel (mtk-tpd)
Usage: python gen_privapp.py <apps dir> <permissions.txt from 'pm list permissions -f'> <out dir>"""
import sys, re, subprocess, pathlib, glob, os

apps, perms_txt, out = map(pathlib.Path, sys.argv[1:4])
aapt = sorted(glob.glob(os.path.expandvars(r"%LOCALAPPDATA%\Android\Sdk\build-tools\*\aapt.exe")))[-1]

# permission -> protection level
level, owner, cur = {}, {}, None
for line in perms_txt.read_text(encoding="utf-8", errors="replace").splitlines():
    m = re.match(r"\+ permission:(\S+)", line)
    if m:
        cur = m.group(1)
    elif cur and line.strip().startswith("package:"):
        owner[cur] = line.split("package:", 1)[1].strip()
    elif cur and "protectionLevel:" in line:
        level[cur] = line.split("protectionLevel:", 1)[1].strip()

entries, report = [], []
for pdir in sorted(p for p in apps.iterdir() if p.is_dir()):
    pkg = pdir.name
    req = set()
    for apk in pdir.glob("*.apk"):
        o = subprocess.run([aapt, "dump", "permissions", str(apk)], capture_output=True, text=True).stdout
        req |= set(re.findall(r"uses-permission: name='([^']+)'", o))
    priv = sorted(p for p in req if "privileged" in level.get(p, ""))
    sig_only = sorted(p for p in req if not owner.get(p, "").startswith("com.future.")
                      and "signature" in level.get(p, "") and "privileged" not in level.get(p, "")
                      and "appop" not in level.get(p, "") and "development" not in level.get(p, ""))
    entries.append((pkg, priv))
    report.append(f"{pkg}: privileged={len(priv)} {priv}\n    signature-only (NOT grantable without the Duoqin platform key)={sig_only}")

x = ['<?xml version="1.0" encoding="utf-8"?>',
     '<!-- Generated by aosp/rom-repack/gen_privapp.py - FutureOS priv-app allowlist -->', '<permissions>']
for pkg, priv in entries:
    x.append(f'    <privapp-permissions package="{pkg}">')
    x += [f'        <permission name="{p}"/>' for p in priv]
    x.append('    </privapp-permissions>')
x.append('</permissions>')
(out / "etc/permissions").mkdir(parents=True, exist_ok=True)
(out / "etc/permissions/privapp-permissions-futureos.xml").write_text("\n".join(x) + "\n", encoding="utf-8")

(out / "etc/excluded-input-devices.xml").write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<!-- FutureOS is keypad-only: InputManager ignores the touch panel. Remove this file to bring touch back. -->\n'
    '<devices>\n    <device name="mtk-tpd" />\n</devices>\n', encoding="utf-8")
(out / "privapp-report.txt").write_text("\n".join(report) + "\n", encoding="utf-8")
print("\n".join(report))
