"""Generate compileOnly Java stubs for FutureSystemUI from framework-contract.txt (dex_contract.py output).
The stubs are never packaged: at runtime the device's real framework classes are used, so method
signatures must match the device exactly - that is why they come from the device's framework.jar.
Usage: python gen_stubs.py framework-contract.txt <out java dir>"""
import re, sys, pathlib

PRIM = {"V": "void", "Z": "boolean", "B": "byte", "C": "char", "S": "short", "I": "int", "J": "long", "F": "float", "D": "double"}
def jt(d):
    if d.startswith("["): return jt(d[1:]) + "[]"
    if d in PRIM: return PRIM[d]
    return d[1:-1].replace("/", ".").replace("$", ".")

contract, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
cls, methods = None, {}
for line in contract.read_text().splitlines():
    m = re.match(r"## (\S+) ", line)
    if m: cls = m.group(1); methods[cls] = []; continue
    m = re.match(r"\s+(\S+)\((.*)\) -> (\S+)", line)
    if m and cls:
        args = [a.strip() for a in m.group(2).split(",") if a.strip()]
        methods[cls].append((m.group(1), [jt(a) for a in args], jt(m.group(3))))

def default(t): return {"void": "", "boolean": "return false;", "int": "return 0;", "long": "return 0;"}.get(t, "return null;" if t not in PRIM.values() else "return 0;")
used = set()
def write(fqcn, body):
    pkg, name = fqcn.rsplit(".", 1)
    p = out / pkg.replace(".", "/") / f"{name}.java"; p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(f"// GENERATED by aosp/rom-repack/gen_stubs.py from the device framework.jar - compileOnly, never packaged\npackage {pkg};\n\n{body}\n")

for iface in ["Lcom/android/internal/statusbar/IStatusBar;", "Lcom/android/internal/statusbar/IStatusBarService;"]:
    fq = jt(iface); name = fq.rsplit(".", 1)[1]
    sigs = []
    for n, a, r in methods[iface]:
        if n == "asBinder": continue
        for t in a + [r]: used.add(t.replace("[]", ""))
        params = ", ".join(f"{t} p{i}" for i, t in enumerate(a))
        sigs.append(f"    {r} {n}({params}) throws android.os.RemoteException;")
    body = (f"public interface {name} extends android.os.IInterface {{\n" + "\n".join(sigs) +
            f"\n\n    public static abstract class Stub extends android.os.Binder implements {name} {{\n"
            f"        public Stub() {{ throw new RuntimeException(\"stub\"); }}\n"
            f"        public static {name} asInterface(android.os.IBinder b) {{ throw new RuntimeException(\"stub\"); }}\n"
            f"        @Override public android.os.IBinder asBinder() {{ return this; }}\n    }}\n}}")
    write(fq, body)

# hidden types referenced by the two interfaces: empty placeholders (the real classes come from the device)
SDK_PREFIX = ("java.", "android.os.", "android.content.ComponentName", "android.os.Bundle", "android.graphics.Rect",
              "android.content.Intent", "android.net.Uri", "android.app.Notification", "android.graphics.drawable.Icon",
              "android.service.notification.StatusBarNotification", "android.app.PendingIntent", "android.view.KeyEvent",
              "android.content.pm.ParceledListSlice")
for t in sorted(used):
    if t in PRIM.values() or t.startswith(SDK_PREFIX) or t in (jt("Lcom/android/internal/statusbar/IStatusBar;"),
                                                               jt("Lcom/android/internal/statusbar/IStatusBarService;")):
        continue
    if t.startswith("android.") and t.split(".")[-1][0] == "I" and t.split(".")[-1][1].isupper():
        write(t, f"public interface {t.rsplit('.',1)[1]} extends android.os.IInterface {{}}")
    else:
        write(t, f"public class {t.rsplit('.',1)[1]} {{}}")
    print("placeholder", t)

# CommandQueue (app source, like AOSP SystemUI): implements every IStatusBar method on the binder thread and
# re-posts it to the main thread as a Callbacks default method, so features override only what they need.
if len(sys.argv) > 3:
    app = pathlib.Path(sys.argv[3])
    cb, impl = [], []
    for n, a, r in methods["Lcom/android/internal/statusbar/IStatusBar;"]:
        if n == "asBinder": continue
        params = ", ".join(f"{t} p{i}" for i, t in enumerate(a)); names = ", ".join(f"p{i}" for i in range(len(a)))
        cb.append(f"        default void {n}({params}) {{}}")
        impl.append(f"    @Override public void {n}({params}) {{ post(c -> c.{n}({names})); }}")
    (app / "CommandQueue.java").write_text(
        "// GENERATED by aosp/rom-repack/gen_stubs.py from the device framework.jar (IStatusBar on this device)\n"
        "package com.future.systemui;\n\nimport android.os.Handler;\nimport android.os.Looper;\n"
        "import java.util.concurrent.CopyOnWriteArrayList;\n\n"
        "/** The IStatusBar binder system_server calls. Every call is re-posted to the main thread. */\n"
        "public final class CommandQueue extends com.android.internal.statusbar.IStatusBar.Stub {\n"
        "    public interface Callbacks {\n" + "\n".join(cb) + "\n    }\n\n"
        "    private final Handler main = new Handler(Looper.getMainLooper());\n"
        "    private final CopyOnWriteArrayList<Callbacks> callbacks = new CopyOnWriteArrayList<>();\n"
        "    public void addCallback(Callbacks c) { callbacks.add(c); }\n"
        "    public void removeCallback(Callbacks c) { callbacks.remove(c); }\n"
        "    private interface Call { void run(Callbacks c); }\n"
        "    private void post(Call call) { main.post(() -> { for (Callbacks c : callbacks) {\n"
        "        try { call.run(c); } catch (Throwable t) { android.util.Log.e(\"FutureSystemUI\", \"callback failed\", t); } } }); }\n\n"
        + "\n".join(impl) + "\n}\n", encoding="utf-8")
    print("CommandQueue:", len(impl), "methods")
