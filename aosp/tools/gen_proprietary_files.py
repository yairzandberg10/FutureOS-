#!/usr/bin/env python3
"""
Drafts a LineageOS-style proprietary-files.txt from an extracted firmware tree
(fs/vendor, fs/odm, ...). A starting point to review by hand, not a final list:
everything under vendor/ and odm/ is a candidate, grouped by subsystem so the
MediaTek pieces that matter most (IMS/RIL, camera, audio, GPU) are easy to find.

Usage: gen_proprietary_files.py <extracted fs dir>  > proprietary-files.txt
"""
import os
import re
import sys

PARTITIONS = ("vendor", "odm")
# Built from source in the device tree / AOSP, or regenerated: not blobs.
SKIP = re.compile(r"(^|/)(build\.prop|default\.prop|.*\.(apex|capex)$|etc/selinux/|"
                  r"lib(64)?/vndk|etc/vintf/manifest\.xml$|etc/fstab\.|bin/toybox_vendor$|bin/sh$)")
GROUPS = [
    ("IMS / RIL / modem (VoLTE)", r"ims|volte|ril|mdlog|ccci|md_?init|fusion|mtkrild|wfca|nvram|xcap|vilte|telephony"),
    ("Camera", r"camera|mtkcam|imgsensor|libcam|cam_|3a|isp|lens|af_|flash"),
    ("Audio", r"audio|aurisys|speech|bessound|libaudio"),
    ("Graphics / display (Mali, gralloc, hwc)", r"mali|egl|gles|vulkan|gralloc|hwcomposer|libged|libgpu|pq|aal"),
    ("Media / codecs", r"omx|codec2|c2|vpu|libvcodec|mtk_venc|mtk_vdec|libmtkcodec"),
    ("Connectivity (Wi-Fi / BT / GPS / FM)", r"wifi|wlan|wmt|bluetooth|bt_|gnss|gps|mnld|fm_|conn"),
    ("Sensors", r"sensor|hub"),
    ("Keypad / input / IR", r"kpd|keylayout|\.kl$|\.kcm$|idc|consumerir|\bir\b"),
    ("Power / thermal / charger", r"thermal|power|charger|battery|perf|fpsgo"),
    ("Security (TEE, keymaster, DRM)", r"keymaster|keymint|gatekeeper|tee|trustonic|microtrust|kinibi|drm|widevine|teei"),
]


def classify(path):
    low = path.lower()
    for name, pattern in GROUPS:
        if re.search(pattern, low):
            return name
    return "Other"


def main():
    root = sys.argv[1]
    groups = {}
    for part in PARTITIONS:
        base = os.path.join(root, part)
        if not os.path.isdir(base):
            continue
        for dirpath, _, files in os.walk(base):
            for fn in files:
                rel = os.path.relpath(os.path.join(dirpath, fn), root).replace(os.sep, "/")
                if SKIP.search(rel):
                    continue
                groups.setdefault(classify(rel), []).append(rel)
    print("# Draft generated by aosp/tools/gen_proprietary_files.py - review by hand.")
    print("# Keep IMS/RIL, camera and modem blobs exactly as in stock (same Android 12 vendor).")
    for name in [g[0] for g in GROUPS] + ["Other"]:
        if name in groups:
            print(f"\n# {name}")
            for rel in sorted(groups[name]):
                print(rel)


if __name__ == "__main__":
    main()
