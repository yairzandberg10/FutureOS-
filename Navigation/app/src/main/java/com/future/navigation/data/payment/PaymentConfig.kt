object PaymentConfig {

    const val RAVKAV_PHONE_LOADING = "037207406"

    const val MIN_LOAD_AGOROT = 3000
    const val MAX_LOAD_AGOROT = 30000

    /**
     * המספר לחיוג. מספר הרב-קו בא אחרי ";" - Telecom מחבר את השיחה ומחכה, ומסך
     * השיחה של החייגן מציע לשלוח אותו כטונים ברגע שהמענה הקולי מבקש (ר'
     * CallService.onPostDialWait באפליקציית החייגן). כך אף ספרה לא נשלחת
     * באמצע ההודעה המוקלטת ונבלעת בתפריט הלא נכון.
     */
    fun dialString(ravKavNumber: String): String {
        val card = ravKavNumber.filter { it.isDigit() }
        return if (card.isEmpty()) RAVKAV_PHONE_LOADING else "$RAVKAV_PHONE_LOADING;$card"
    }
}
